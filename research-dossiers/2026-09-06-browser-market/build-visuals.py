# ---------------------------------------------------------------- watercolor plates
rng = random.Random(7)
W, H, S = 900, 700, 2  # logical size, supersample

class Plate:
    def __init__(self): self.img = Image.new('RGBA', (W * S, H * S), (0, 0, 0, 0))
    def wash(self, pts, color, alpha=95, blur=7, jitter=10):
        # translucent wash: slightly displaced, blurred polygon, bleeding past the lines
        pts = [(x + rng.uniform(-jitter, jitter), y + rng.uniform(-jitter, jitter)) for x, y in pts]
        layer = Image.new('RGBA', self.img.size, (0, 0, 0, 0)); d = ImageDraw.Draw(layer)
        d.polygon([(x * S, y * S) for x, y in pts], fill=color + (alpha,))
        layer = layer.filter(ImageFilter.GaussianBlur(blur * S / 2))
        self.img = Image.alpha_composite(self.img, layer)
    def ellipse_pts(self, cx, cy, rx, ry, n=36, wob=0.07):
        return [(cx + rx * math.cos(2 * math.pi * k / n) * (1 + rng.uniform(-wob, wob)),
                 cy + ry * math.sin(2 * math.pi * k / n) * (1 + rng.uniform(-wob, wob))) for k in range(n)]
    def rect_pts(self, x, y, w, h, step=30, wob=3):
        p = []
        for t in range(0, int(w), step): p.append((x + t, y))
        for t in range(0, int(h), step): p.append((x + w, y + t))
        for t in range(0, int(w), step): p.append((x + w - t, y + h))
        for t in range(0, int(h), step): p.append((x, y + h - t))
        return p
    def line(self, pts, width=3.2, color=(39, 35, 30), closed=False, wob=1.6):
        # wobbly ink: densify, jitter, draw with varying width
        out = []
        P = pts + ([pts[0]] if closed else [])
        for (x1, y1), (x2, y2) in zip(P, P[1:]):
            n = max(2, int(math.hypot(x2 - x1, y2 - y1) / 12))
            for k in range(n): out.append((x1 + (x2 - x1) * k / n + rng.uniform(-wob, wob), y1 + (y2 - y1) * k / n + rng.uniform(-wob, wob)))
        out.append(P[-1])
        d = ImageDraw.Draw(self.img)
        for a, b in zip(out, out[1:]):
            w = width * rng.uniform(0.7, 1.3) * S
            d.line([(a[0] * S, a[1] * S), (b[0] * S, b[1] * S)], fill=color + (225,), width=max(1, int(w)))
            r = w / 2; d.ellipse([a[0] * S - r, a[1] * S - r, a[0] * S + r, a[1] * S + r], fill=color + (225,))
    def circle(self, cx, cy, r, fill=None, **kw):
        pts = self.ellipse_pts(cx, cy, r, r, 28, 0.05)
        if fill: self.wash(pts, fill, kw.get('alpha', 100))
        self.line(pts, closed=True, width=kw.get('width', 3))
    def ell(self, cx, cy, rx, ry, fill=None, **kw):
        pts = self.ellipse_pts(cx, cy, rx, ry, 32, 0.05)
        if fill: self.wash(pts, fill, kw.get('alpha', 100))
        self.line(pts, closed=True, width=kw.get('width', 3))
    def box(self, x, y, w, h, fill=None, **kw):
        pts = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
        if fill: self.wash([(a - 4, b - 4) if i < 2 else (a + 4, b + 4) for i, (a, b) in enumerate(pts)], fill, kw.get('alpha', 100))
        self.line(pts, closed=True, width=kw.get('width', 3))
    def person(self, x, y, s=1.0, shirt=(157, 76, 63)):
        self.circle(x, y - 70 * s, 22 * s, (226, 186, 150))
        self.wash([(x - 28 * s, y - 42 * s), (x + 28 * s, y - 42 * s), (x + 34 * s, y + 50 * s), (x - 34 * s, y + 50 * s)], shirt, 120)
        self.line([(x - 28 * s, y - 42 * s), (x + 28 * s, y - 42 * s), (x + 34 * s, y + 50 * s), (x - 34 * s, y + 50 * s)], closed=True)
        self.line([(x - 34 * s, y + 50 * s), (x - 38 * s, y + 100 * s)]); self.line([(x + 34 * s, y + 50 * s), (x + 38 * s, y + 100 * s)])
    def coin(self, x, y, r=20): self.circle(x, y, r, (214, 170, 70), width=2.5); self.line([(x - r / 3, y), (x + r / 3, y)], width=2)
    def save(self, name):
        im = self.img.resize((W, H), Image.LANCZOS)
        # guarantee a clean transparent margin
        px = im.load()
        for y in range(H):
            for x in range(W):
                if x < 24 or x >= W - 24 or y < 24 or y >= H - 24: px[x, y] = (0, 0, 0, 0)
        im.save(OUT / name, optimize=True)

