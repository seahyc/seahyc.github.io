# ---------------------------------------------------------------- SVG helpers
def esc(s): return s.replace('&', '&amp;').replace('<', '&lt;')
def T(x, y, s, size=18, anchor='start', fill=INK, weight='normal', style='normal'):
    return f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" text-anchor="{anchor}" fill="{fill}" font-weight="{weight}" font-style="{style}">{esc(s)}</text>'
def R(x, y, w, h, fill='none', stroke='none', sw=1.5, rx=6, op=1):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" opacity="{op}"/>'
def C(x, y, r, fill='none', stroke='none', sw=2):
    return f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'
def svg(w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{esc(title)}">'
            + body + '</svg>')
def save(name, s): (OUT / name).write_text(s, encoding='utf-8')

